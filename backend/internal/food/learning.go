// UpsertPortionPref learns a user's typical portion size for a food. Skips
// entirely (no-op) for a non-positive weight — that's not a usable signal.
func (s *PGStore) UpsertPortionPref(ctx context.Context, userID, foodName string, weightG float64, mealType string) error {
	if weightG <= 0 {
		return nil
	}
	var mealTypeArg *string
	if mealType != "" {
		mealTypeArg = &mealType
	}
	_, err := s.q.Exec(ctx, `INSERT INTO user_portion_prefs
		(user_id, food_name, typical_weight_g, logged_count, typical_meal_type, last_logged)
		VALUES ($1, $2, $3, 1, $4, now())
		ON CONFLICT (user_id, food_name) DO UPDATE SET
			typical_weight_g = (user_portion_prefs.typical_weight_g * user_portion_prefs.logged_count + EXCLUDED.typical_weight_g)
				/ (user_portion_prefs.logged_count + 1),
			logged_count = user_portion_prefs.logged_count + 1,
			last_logged = now(),
			typical_meal_type = COALESCE(
				(SELECT meal_type FROM food_logs
				 WHERE user_id = $1 AND food_name = $2 AND meal_type IS NOT NULL
				 GROUP BY meal_type ORDER BY count(*) DESC LIMIT 1),
				EXCLUDED.typical_meal_type)`,
		userID, foodName, weightG, mealTypeArg)
	return err
}

// RecordFoodNameCorrection is only meaningful when the name actually changed.
func (s *PGStore) RecordFoodNameCorrection(ctx context.Context, userID, original, corrected string) error {
	if original == "" || corrected == "" || original == corrected {
		return nil
	}
	_, err := s.q.Exec(ctx,
		`INSERT INTO food_name_corrections (user_id, original_name, corrected_name) VALUES ($1, $2, $3)`,
		userID, original, corrected)
	return err
}

// FlagBrainRebuildIfDue sets needs_rebuild once 5+ new logs have landed
// since the last rebuild. No-op (0 rows) if the user has no ai_user_brain
// row yet — the first rebuild will create one.
func (s *PGStore) FlagBrainRebuildIfDue(ctx context.Context, userID string) error {
	_, err := s.q.Exec(ctx, `UPDATE ai_user_brain SET needs_rebuild = true
		WHERE user_id = $1 AND needs_rebuild = false
		AND (SELECT count(*) FROM food_logs fl
		     WHERE fl.user_id = $1
		       AND fl.created_at > COALESCE(ai_user_brain.last_rebuilt, 'epoch'::timestamptz)) >= 5`,
		userID)
	return err
}

// DetectMealMemory is a bounded, best-effort heuristic for the (date,
// mealType) that was just logged into: if the same set of 2+ foods has been
// logged for this meal_type on 3+ distinct days (including today) in the
// last 30 days, it creates (or bumps) an auto_generated saved_meal.
//
// ponytail: one repeating combo per meal_type is the common case; a second,
// distinct repeating combo for the same meal_type creates a second
// auto-generated entry rather than merging into the first — acceptable.
func (s *PGStore) DetectMealMemory(ctx context.Context, userID, date, mealType string) error {
	todaysSet, err := s.distinctFoodNames(ctx, userID, date, mealType)
	if err != nil {
		return err
	}
	if len(todaysSet) < 2 {
		return nil
	}
	sort.Strings(todaysSet)

	matchCount, err := s.matchingDayCount(ctx, userID, date, mealType, todaysSet)
	if err != nil {
		return err
	}
	if matchCount < 3 {
		return nil
	}

	matchedID, err := s.findAutoGeneratedSavedMeal(ctx, userID, mealType, todaysSet)
	if err != nil {
		return err
	}
	if matchedID != "" {
		_, err := s.q.Exec(ctx,
			`UPDATE saved_meals SET logged_count = logged_count + 1, last_logged = now() WHERE id = $1`,
			matchedID)
		return err
	}
	return s.createAutoGeneratedSavedMeal(ctx, userID, date, mealType, todaysSet)
}

func (s *PGStore) distinctFoodNames(ctx context.Context, userID, date, mealType string) ([]string, error) {
	rows, err := s.q.Query(ctx, `SELECT DISTINCT food_name FROM food_logs
		WHERE user_id = $1 AND date = $2::date AND meal_type = $3`, userID, date, mealType)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var names []string
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			return nil, err
		}
		// Normalize for comparison only — findAutoGeneratedSavedMeal/createAutoGeneratedSavedMeal
		// still persist the original-cased food_name for saved_meal_items display text.
		names = append(names, strings.ToLower(strings.TrimSpace(name)))
	}
	return names, rows.Err()
}

// matchingDayCount counts distinct dates in the last 30 days (including
// today) whose logged food-name set for this meal_type exactly matches
// todaysSet (already sorted).
func (s *PGStore) matchingDayCount(ctx context.Context, userID, date, mealType string, todaysSet []string) (int, error) {
	rows, err := s.q.Query(ctx, `SELECT date, food_name FROM food_logs
		WHERE user_id = $1 AND meal_type = $2 AND date BETWEEN ($3::date - 30) AND $3::date`,
		userID, mealType, date)
	if err != nil {
		return 0, err
	}
	defer rows.Close()
	byDate := map[string]map[string]bool{}
	for rows.Next() {
		var d time.Time
		var name string
		if err := rows.Scan(&d, &name); err != nil {
			return 0, err
		}
		key := d.Format("2006-01-02")
		if byDate[key] == nil {
			byDate[key] = map[string]bool{}
		}
		byDate[key][strings.ToLower(strings.TrimSpace(name))] = true
	}
	if err := rows.Err(); err != nil {
		return 0, err
	}

	count := 0
	for _, names := range byDate {
		list := make([]string, 0, len(names))
		for n := range names {
			list = append(list, n)
		}
		sort.Strings(list)
		if slices.Equal(list, todaysSet) {
			count++
		}
	}
	return count, nil
}

// findAutoGeneratedSavedMeal returns the id of an existing auto_generated
// saved_meal for this user/meal_type whose item set exactly matches
// todaysSet, or "" if none matches.
func (s *PGStore) findAutoGeneratedSavedMeal(ctx context.Context, userID, mealType string, todaysSet []string) (string, error) {
	rows, err := s.q.Query(ctx, `SELECT id FROM saved_meals
		WHERE user_id = $1 AND meal_type = $2 AND auto_generated = true`, userID, mealType)
	if err != nil {
		return "", err
	}
	var ids []string
	for rows.Next() {
		var id string
		if err := rows.Scan(&id); err != nil {
			rows.Close()
			return "", err
		}
		ids = append(ids, id)
	}
	if err := rows.Err(); err != nil {
		return "", err
	}
	rows.Close()

	for _, id := range ids {
		itemRows, err := s.q.Query(ctx, `SELECT food_name FROM saved_meal_items WHERE saved_meal_id = $1`, id)
		if err != nil {
			return "", err
		}
		var items []string
		for itemRows.Next() {
			var name string
			if err := itemRows.Scan(&name); err != nil {
				itemRows.Close()
				return "", err
			}
			items = append(items, strings.ToLower(strings.TrimSpace(name)))
		}
		if err := itemRows.Err(); err != nil {
			itemRows.Close()
			return "", err
		}
		itemRows.Close()

		sort.Strings(items)
		if slices.Equal(items, todaysSet) {
			return id, nil
		}
	}
	return "", nil
}

// createAutoGeneratedSavedMeal builds a new saved_meal + items from today's
// matching food_logs rows. If a food name appears twice today with
// different values, the first occurrence is used (documented simplification).
func (s *PGStore) createAutoGeneratedSavedMeal(ctx context.Context, userID, date, mealType string, todaysSet []string) error {
	rows, err := s.q.Query(ctx, `SELECT food_name, quantity, calories, protein, carbs, fat, fibre
		FROM food_logs WHERE user_id = $1 AND date = $2::date AND meal_type = $3
		ORDER BY created_at ASC`, userID, date, mealType)
	if err != nil {
		return err
	}
	type item struct {
		quantity                             *float64
		calories, protein, carbs, fat, fibre float64
	}
	firstByName := map[string]item{}
	var order []string
	var sumCal, sumProtein, sumCarbs, sumFat, sumFibre float64
	for rows.Next() {
		var name string
		var it item
		if err := rows.Scan(&name, &it.quantity, &it.calories, &it.protein, &it.carbs, &it.fat, &it.fibre); err != nil {
			rows.Close()
			return err
		}
		sumCal += it.calories
		sumProtein += it.protein
		sumCarbs += it.carbs
		sumFat += it.fat
		sumFibre += it.fibre
		if _, ok := firstByName[name]; !ok {
			firstByName[name] = it
			order = append(order, name)
		}
	}
	if err := rows.Err(); err != nil {
		rows.Close()
		return err
	}
	rows.Close()

	tx, err := s.q.Begin(ctx)
	if err != nil {
		return err
	}
	defer tx.Rollback(ctx) // no-op once committed

	var savedMealID string
	err = tx.QueryRow(ctx, `INSERT INTO saved_meals
		(user_id, name, meal_type, total_calories, total_protein, total_carbs, total_fat, total_fibre,
		 logged_count, last_logged, auto_generated)
		VALUES ($1, $2, $3, $4, $5, $6, $7, $8, 1, now(), true) RETURNING id`,
		userID, "Your usual "+mealType, mealType, sumCal, sumProtein, sumCarbs, sumFat, sumFibre).
		Scan(&savedMealID)
	if err != nil {
		return err
	}
	for _, name := range order {
		it := firstByName[name]
		qty := 0.0
		if it.quantity != nil {
			qty = *it.quantity
		}
		_, err = tx.Exec(ctx, `INSERT INTO saved_meal_items
			(saved_meal_id, food_name, quantity_g, calories, protein, carbs, fat, fibre)
			VALUES ($1, $2, $3, $4, $5, $6, $7, $8)`,
			savedMealID, name, qty, it.calories, it.protein, it.carbs, it.fat, it.fibre)
		if err != nil {
			return err
		}
	}
	return tx.Commit(ctx)
}
