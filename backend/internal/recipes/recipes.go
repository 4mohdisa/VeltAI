// Package recipes implements user-created recipes and saved meals: build once
// from a list of ingredients/items, log servings later straight into
// food_logs. Self-contained — writes food_logs directly via SQL, no
// dependency on the food package.
package recipes

import (
	"context"
	"errors"
	"net/http"
	"strings"
	"time"

	"lumo/backend/internal/auth"
	"lumo/backend/internal/config"
	"lumo/backend/internal/httpx"
)

var ErrNotFound = errors.New("not found")

type Ingredient struct {
	FoodName  string  `json:"food_name"`
	QuantityG float64 `json:"quantity_g"`
	Calories  float64 `json:"calories"`
	Protein   float64 `json:"protein"`
	Carbs     float64 `json:"carbs"`
	Fat       float64 `json:"fat"`
	Fibre     float64 `json:"fibre"`
}

type Recipe struct {
	ID            string       `json:"id"`
	UserID        string       `json:"user_id"`
	Name          string       `json:"name"`
	Description   *string      `json:"description"`
	TotalCalories float64      `json:"total_calories"`
	TotalProtein  float64      `json:"total_protein"`
	TotalCarbs    float64      `json:"total_carbs"`
	TotalFat      float64      `json:"total_fat"`
	TotalFibre    float64      `json:"total_fibre"`
	ServingCount  int          `json:"serving_count"`
	Ingredients   []Ingredient `json:"ingredients"`
	CreatedAt     time.Time    `json:"created_at"`
	UpdatedAt     time.Time    `json:"updated_at"`
}

type MealItem struct {
	FoodName  string  `json:"food_name"`
	QuantityG float64 `json:"quantity_g"`
	Calories  float64 `json:"calories"`
	Protein   float64 `json:"protein"`
	Carbs     float64 `json:"carbs"`
	Fat       float64 `json:"fat"`
	Fibre     float64 `json:"fibre"`
}

type SavedMeal struct {
	ID            string     `json:"id"`
	UserID        string     `json:"user_id"`
	Name          string     `json:"name"`
	MealType      *string    `json:"meal_type"`
	TotalCalories float64    `json:"total_calories"`
	TotalProtein  float64    `json:"total_protein"`
	TotalCarbs    float64    `json:"total_carbs"`
	TotalFat      float64    `json:"total_fat"`
	TotalFibre    float64    `json:"total_fibre"`
	Items         []MealItem `json:"items"`
	LoggedCount   int        `json:"logged_count"`
	LastLogged    *time.Time `json:"last_logged"`
	AutoGenerated bool       `json:"auto_generated"`
	CreatedAt     time.Time  `json:"created_at"`
}

type Store interface {
	ListRecipes(ctx context.Context, userID string) ([]Recipe, error)
	CreateRecipe(ctx context.Context, userID, name string, description *string, servingCount int, ingredients []Ingredient) (Recipe, error)
	GetRecipe(ctx context.Context, id string) (*Recipe, error)
	UpdateRecipe(ctx context.Context, id string, name, description *string, servingCount *int, ingredients []Ingredient) (Recipe, error)
	DeleteRecipe(ctx context.Context, id string) error
	LogRecipe(ctx context.Context, recipeID, mealType, date string, servings float64) (count int, err error)
	GetRecipeOwner(ctx context.Context, id string) (string, error)

	ListSavedMeals(ctx context.Context, userID string) ([]SavedMeal, error)
	CreateSavedMeal(ctx context.Context, userID, name string, mealType *string, items []MealItem) (SavedMeal, error)
	LogSavedMeal(ctx context.Context, id, mealType, date string) (count int, err error)
	DeleteSavedMeal(ctx context.Context, id string) error
	GetSavedMealOwner(ctx context.Context, id string) (string, error)
}

func Register(mux *http.ServeMux, s Store) {
	h := &handler{store: s}
	mux.HandleFunc("GET /api/recipes", h.listRecipes)
	mux.HandleFunc("POST /api/recipes", h.createRecipe)
	mux.HandleFunc("GET /api/recipes/{id}", h.getRecipe)
	mux.HandleFunc("PATCH /api/recipes/{id}", h.patchRecipe)
	mux.HandleFunc("DELETE /api/recipes/{id}", h.deleteRecipe)
	mux.HandleFunc("POST /api/recipes/{id}/log", h.logRecipe)

	mux.HandleFunc("GET /api/saved-meals", h.listSavedMeals)
	mux.HandleFunc("POST /api/saved-meals", h.createSavedMeal)
	mux.HandleFunc("POST /api/saved-meals/{id}/log", h.logSavedMeal)
	mux.HandleFunc("DELETE /api/saved-meals/{id}", h.deleteSavedMeal)
}

type handler struct{ store Store }

func validDate(s string) bool {
	_, err := time.Parse("2006-01-02", s)
	return err == nil
}

// authorize writes 404/403/500 and returns false unless the row exists and
// belongs to the authenticated user. Same shape as food.authorize — cannot be
// imported cross-package (unexported there), reimplemented here.
func authorize(w http.ResponseWriter, r *http.Request, getOwner func(context.Context, string) (string, error), id string) bool {
	owner, err := getOwner(r.Context(), id)
	switch {
	case errors.Is(err, ErrNotFound):
		httpx.Error(w, http.StatusNotFound, "not found")
	case err != nil:
		httpx.Error(w, http.StatusInternalServerError, "lookup failed")
	case owner != auth.UserID(r.Context()):
		httpx.Error(w, http.StatusForbidden, "forbidden")
	default:
		return true
	}
	return false
}

// --- recipes ---

func (h *handler) listRecipes(w http.ResponseWriter, r *http.Request) {
	recs, err := h.store.ListRecipes(r.Context(), auth.UserID(r.Context()))
	if err != nil {
		httpx.Error(w, http.StatusInternalServerError, "failed to list recipes")
		return
	}
	if recs == nil {
		recs = []Recipe{}
	}
	httpx.JSON(w, http.StatusOK, recs)
}

type createRecipeReq struct {
	Name         string       `json:"name"`
	Description  *string      `json:"description"`
	ServingCount *int         `json:"serving_count"`
	Ingredients  []Ingredient `json:"ingredients"`
}

func (h *handler) createRecipe(w http.ResponseWriter, r *http.Request) {
	var req createRecipeReq
	if err := httpx.Decode(r, &req); err != nil {
		httpx.Error(w, http.StatusBadRequest, err.Error())
		return
	}
	if strings.TrimSpace(req.Name) == "" {
		httpx.Error(w, http.StatusBadRequest, "name is required")
		return
	}
	if len(req.Ingredients) == 0 {
		httpx.Error(w, http.StatusBadRequest, "ingredients are required")
		return
	}
	servingCount := 1
	if req.ServingCount != nil && *req.ServingCount > 0 {
		servingCount = *req.ServingCount
	}
	rec, err := h.store.CreateRecipe(r.Context(), auth.UserID(r.Context()), req.Name, req.Description, servingCount, req.Ingredients)
	if err != nil {
		httpx.Error(w, http.StatusInternalServerError, "failed to create recipe")
		return
	}
	httpx.JSON(w, http.StatusCreated, rec)
}

func (h *handler) getRecipe(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	if !authorize(w, r, h.store.GetRecipeOwner, id) {
		return
	}
	rec, err := h.store.GetRecipe(r.Context(), id)
	if err != nil {
		httpx.Error(w, http.StatusInternalServerError, "failed to load recipe")
		return
	}
	if rec == nil {
		httpx.Error(w, http.StatusNotFound, "not found")
		return
	}
	httpx.JSON(w, http.StatusOK, rec)
}

type patchRecipeReq struct {
	Name         *string      `json:"name"`
	Description  *string      `json:"description"`
	ServingCount *int         `json:"serving_count"`
	Ingredients  []Ingredient `json:"ingredients"`
}

func (h *handler) patchRecipe(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	if !authorize(w, r, h.store.GetRecipeOwner, id) {
		return
	}
	var req patchRecipeReq
	if err := httpx.Decode(r, &req); err != nil {
		httpx.Error(w, http.StatusBadRequest, err.Error())
		return
	}
	if req.Name != nil && strings.TrimSpace(*req.Name) == "" {
		httpx.Error(w, http.StatusBadRequest, "name must not be empty")
		return
	}
	if req.ServingCount != nil && *req.ServingCount <= 0 {
		httpx.Error(w, http.StatusBadRequest, "serving_count must be greater than 0")
		return
	}
	rec, err := h.store.UpdateRecipe(r.Context(), id, req.Name, req.Description, req.ServingCount, req.Ingredients)
	if err != nil {
		httpx.Error(w, http.StatusInternalServerError, "failed to update recipe")
		return
	}
	httpx.JSON(w, http.StatusOK, rec)
}

func (h *handler) deleteRecipe(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	if !authorize(w, r, h.store.GetRecipeOwner, id) {
		return
	}
	if err := h.store.DeleteRecipe(r.Context(), id); err != nil {
		httpx.Error(w, http.StatusInternalServerError, "failed to delete recipe")
		return
	}
	httpx.JSON(w, http.StatusOK, map[string]bool{"deleted": true})
}

type logReq struct {
	MealType string  `json:"meal_type"`
	Servings float64 `json:"servings"`
	Date     string  `json:"date"`
}

func (h *handler) logRecipe(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	if !authorize(w, r, h.store.GetRecipeOwner, id) {
		return
	}
	var req logReq
	if err := httpx.Decode(r, &req); err != nil {
		httpx.Error(w, http.StatusBadRequest, err.Error())
		return
	}
	servings := req.Servings
	if servings < 0 {
		httpx.Error(w, http.StatusBadRequest, "servings must be greater than 0")
		return
	}
	if servings == 0 {
		servings = 1
	}
	date := req.Date
	if date == "" {
		date = config.Today()
	} else if !validDate(date) {
		httpx.Error(w, http.StatusBadRequest, "date must be YYYY-MM-DD")
		return
	}
	count, err := h.store.LogRecipe(r.Context(), id, req.MealType, date, servings)
	if err != nil {
		httpx.Error(w, http.StatusInternalServerError, "failed to log recipe")
		return
	}
	httpx.JSON(w, http.StatusOK, map[string]int{"entries_created": count})
}

