// --- D) learning hooks --------------------------------------------------------

func (f *fakeStore) mostFrequentMealType(userID, foodName string) string {
	counts := map[string]int{}
	for _, l := range f.logs {
		if l.UserID == userID && l.FoodName == foodName && l.MealType != nil && *l.MealType != "" {
			counts[*l.MealType]++
		}
	}
	best, bestN := "", 0
	for mt, n := range counts {
		if n > bestN {
			best, bestN = mt, n
		}
	}
	return best
}

func (f *fakeStore) UpsertPortionPref(_ context.Context, userID, foodName string, weightG float64, mealType string) error {
	if weightG <= 0 {
		return nil
	}
	if f.portionPrefs == nil {
		f.portionPrefs = map[string]*food.PortionPref{}
	}
	key := userID + "|" + foodName
	p, ok := f.portionPrefs[key]
	if !ok {
		w := weightG
		var mt *string
		if mealType != "" {
			m := mealType
			mt = &m
		}
		f.portionPrefs[key] = &food.PortionPref{TypicalWeightG: &w, LoggedCount: 1, TypicalMealType: mt}
		return nil
	}
	existing := 0.0
	if p.TypicalWeightG != nil {
		existing = *p.TypicalWeightG
	}
	avg := (existing*float64(p.LoggedCount) + weightG) / float64(p.LoggedCount+1)
	p.TypicalWeightG = &avg
	p.LoggedCount++
	mt := f.mostFrequentMealType(userID, foodName)
	if mt == "" {
		mt = mealType
	}
	if mt != "" {
		p.TypicalMealType = &mt
	}
	return nil
}

func (f *fakeStore) RecordFoodNameCorrection(_ context.Context, userID, original, corrected string) error {
	if original == "" || corrected == "" || original == corrected {
		return nil
	}
	f.corrections = append(f.corrections, foodNameCorrection{userID, original, corrected})
	return nil
}

func (f *fakeStore) FlagBrainRebuildIfDue(_ context.Context, userID string) error {
	if !f.brainExists[userID] || f.brainNeedsRebuild[userID] {
		return nil
	}
	cutoff := f.brainLastRebuilt[userID] // zero value = epoch, all logs count
	count := 0
	for _, l := range f.logs {
		if l.UserID == userID && l.CreatedAt.After(cutoff) {
			count++
		}
	}
	if count >= 5 {
		if f.brainNeedsRebuild == nil {
			f.brainNeedsRebuild = map[string]bool{}
		}
		f.brainNeedsRebuild[userID] = true
	}
	return nil
}

func sameFoodSet(a map[string]bool, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for _, name := range b {
		if !a[name] {
			return false
		}
	}
	return true
}

// DetectMealMemory mirrors PGStore.DetectMealMemory's logic in-memory, for
// tests only (see food/learning.go for the real SQL-backed version).
func (f *fakeStore) DetectMealMemory(_ context.Context, userID, date, mealType string) error {
	todaySet := map[string]bool{}
	for _, l := range f.logs {
		if l.UserID == userID && l.Date == date && l.MealType != nil && *l.MealType == mealType {
			todaySet[l.FoodName] = true
		}
	}
	if len(todaySet) < 2 {
		return nil
	}
	todaysList := make([]string, 0, len(todaySet))
	for n := range todaySet {
		todaysList = append(todaysList, n)
	}

	d, err := time.Parse("2006-01-02", date)
	if err != nil {
		return err
	}
	cutoff := d.AddDate(0, 0, -30).Format("2006-01-02")

	byDate := map[string]map[string]bool{}
	for _, l := range f.logs {
		if l.UserID != userID || l.MealType == nil || *l.MealType != mealType {
			continue
		}
		if l.Date < cutoff || l.Date > date {
			continue
		}
		if byDate[l.Date] == nil {
			byDate[l.Date] = map[string]bool{}
		}
		byDate[l.Date][l.FoodName] = true
	}
	matchCount := 0
	for _, names := range byDate {
		if sameFoodSet(names, todaysList) {
			matchCount++
		}
	}
	if matchCount < 3 {
		return nil
	}

	for i := range f.savedMeals {
		sm := &f.savedMeals[i]
		if sm.userID != userID || sm.mealType != mealType || !sm.autoGenerated {
			continue
		}
		items := map[string]bool{}
		for _, it := range sm.items {
			items[it.foodName] = true
		}
		if sameFoodSet(items, todaysList) {
			sm.loggedCount++
			sm.lastLogged = time.Now()
			return nil
		}
	}

	firstByName := map[string]food.Log{}
	var order []string
	var sumCal, sumProtein, sumCarbs, sumFat, sumFibre float64
	for _, l := range f.logs {
		if l.UserID != userID || l.Date != date || l.MealType == nil || *l.MealType != mealType {
			continue
		}
		sumCal += l.Calories
		sumProtein += l.Protein
		sumCarbs += l.Carbs
		sumFat += l.Fat
		sumFibre += l.Fibre
		if _, ok := firstByName[l.FoodName]; !ok {
			firstByName[l.FoodName] = l
			order = append(order, l.FoodName)
		}
	}
	f.n++
	sm := fakeSavedMeal{
		id: fmt.Sprintf("meal_%d", f.n), userID: userID,
		name: "Your usual " + mealType, mealType: mealType,
		totalCalories: sumCal, totalProtein: sumProtein, totalCarbs: sumCarbs,
		totalFat: sumFat, totalFibre: sumFibre,
		loggedCount: 1, lastLogged: time.Now(), autoGenerated: true,
	}
	for _, name := range order {
		l := firstByName[name]
		qty := 0.0
		if l.Quantity != nil {
			qty = *l.Quantity
		}
		sm.items = append(sm.items, fakeSavedMealItem{
			foodName: name, quantityG: qty,
			calories: l.Calories, protein: l.Protein, carbs: l.Carbs, fat: l.Fat, fibre: l.Fibre,
		})
	}
	f.savedMeals = append(f.savedMeals, sm)
	return nil
}
