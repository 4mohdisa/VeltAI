// --- A) cuisine ranking -----------------------------------------------------

func (f *fakeStore) UserCuisinePrefs(_ context.Context, userID string) ([]string, []string, error) {
	p, ok := f.cuisinePrefs[userID]
	if !ok {
		return nil, nil, nil
	}
	return p.cuisines, p.dietary, nil
}

func (f *fakeStore) CuisineLibraryNames(_ context.Context, cuisines []string) (map[string]bool, error) {
	out := map[string]bool{}
	if len(cuisines) == 0 {
		return out, nil
	}
	want := map[string]bool{}
	for _, c := range cuisines {
		want[c] = true
	}
	for cuisine, names := range f.libraryFoods {
		if !want[cuisine] {
			continue
		}
		for _, n := range names {
			out[strings.ToLower(n)] = true
		}
	}
	return out, nil
}

