func newMux(s food.Store, sc *food.SearchClient) *http.ServeMux {
	if sc == nil {
		sc = food.NewSearchClient("test-key")
	}
	mux := http.NewServeMux()
	food.Register(mux, s, sc)
	return mux
}

func do(t *testing.T, mux *http.ServeMux, method, path, user string, body any) *httptest.ResponseRecorder {
	t.Helper()
	var buf *bytes.Reader
	if body != nil {
		b, err := json.Marshal(body)
		if err != nil {
			t.Fatalf("marshal body: %v", err)
		}
		buf = bytes.NewReader(b)
	} else {
		buf = bytes.NewReader(nil)
	}
	req := httptest.NewRequest(method, path, buf)
	req = req.WithContext(auth.WithUserID(req.Context(), user))
	rr := httptest.NewRecorder()
	mux.ServeHTTP(rr, req)
	return rr
}

func data[T any](t *testing.T, rr *httptest.ResponseRecorder) T {
	t.Helper()
	var env struct {
		Data  T       `json:"data"`
		Error *string `json:"error"`
	}
	if err := json.Unmarshal(rr.Body.Bytes(), &env); err != nil {
		t.Fatalf("decode envelope: %v (body %s)", err, rr.Body.String())
	}
	return env.Data
}

func str(s string) *string { return &s }

func seedLog(t *testing.T, f *fakeStore, user, date, meal, name string, cal, protein float64) food.Log {
	t.Helper()
	l, err := f.CreateLog(context.Background(), food.Log{
		UserID: user, Date: date, MealType: str(meal), FoodName: name,
		Calories: cal, Protein: protein, Carbs: cal / 10, Fat: cal / 20, Fibre: 1,
	})
	if err != nil {
		t.Fatal(err)
	}
	return l
}

func TestCreateLogUsesAuthUser(t *testing.T) {
	f := &fakeStore{}
	mux := newMux(f, nil)
	rr := do(t, mux, "POST", "/api/food/logs", "user_1", map[string]any{
		"food_name": "Egg", "calories": 78, "user_id": "user_evil", "date": "2026-07-11",
	})
	if rr.Code != http.StatusCreated {
		t.Fatalf("status = %d, want 201 (body %s)", rr.Code, rr.Body.String())
	}
	l := data[food.Log](t, rr)
	if l.UserID != "user_1" {
		t.Errorf("user_id = %q, want user_1 (never from body)", l.UserID)
	}
	if l.FoodName != "Egg" || l.Calories != 78 {
		t.Errorf("unexpected log: %+v", l)
	}
}

