func (f *fakeStore) ListLogs(_ context.Context, userID string, date, meal, status *string) ([]food.Log, error) {
	var out []food.Log
	for _, l := range f.logs {
		if l.UserID != userID {
			continue
		}
		if date != nil && l.Date != *date {
			continue
		}
		if meal != nil && (l.MealType == nil || *l.MealType != *meal) {
			continue
		}
		if status != nil && l.Status != *status {
			continue
		}
		out = append(out, l)
	}
	return out, nil
}

func (f *fakeStore) GetLog(_ context.Context, id string) (food.Log, error) {
	for _, l := range f.logs {
		if l.ID == id {
			return l, nil
		}
	}
	return food.Log{}, food.ErrNotFound
}

func (f *fakeStore) CreateLog(_ context.Context, l food.Log) (food.Log, error) {
	f.n++
	l.ID = fmt.Sprintf("log_%d", f.n)
	l.CreatedAt = time.Now()
	f.logs = append(f.logs, l)
	return l, nil
}

func (f *fakeStore) GetLogOwner(_ context.Context, id string) (string, error) {
	for _, l := range f.logs {
		if l.ID == id {
			return l.UserID, nil
		}
	}
	return "", food.ErrNotFound
}

func (f *fakeStore) UpdateLog(_ context.Context, id string, p food.LogPatch) (food.Log, error) {
	for i, l := range f.logs {
		if l.ID != id {
			continue
		}
		if p.Date != nil {
			l.Date = *p.Date
		}
		if p.MealType != nil {
			l.MealType = p.MealType
		}
		if p.FoodName != nil {
			l.FoodName = *p.FoodName
		}
		if p.Brand != nil {
			l.Brand = p.Brand
		}
		if p.Barcode != nil {
			l.Barcode = p.Barcode
		}
		if p.Quantity != nil {
			l.Quantity = p.Quantity
		}
		if p.Unit != nil {
			l.Unit = p.Unit
		}
		if p.Calories != nil {
			l.Calories = *p.Calories
		}
		if p.Protein != nil {
			l.Protein = *p.Protein
		}
		if p.Carbs != nil {
			l.Carbs = *p.Carbs
		}
		if p.Fat != nil {
			l.Fat = *p.Fat
		}
		if p.Fibre != nil {
			l.Fibre = *p.Fibre
		}
		if p.Source != nil {
			l.Source = p.Source
		}
		f.logs[i] = l
		return l, nil
	}
	return food.Log{}, food.ErrNotFound
}

func (f *fakeStore) DeleteLog(_ context.Context, id string) error {
	f.logs = slices.DeleteFunc(f.logs, func(l food.Log) bool { return l.ID == id })
	return nil
}

func (f *fakeStore) Summary(_ context.Context, userID, date string) (food.Summary, error) {
	s := food.Summary{Date: date}
	for _, l := range f.logs {
		if l.UserID != userID || l.Date != date {
			continue
		}
		s.Calories += l.Calories
		s.Protein += l.Protein
		s.Carbs += l.Carbs
		s.Fat += l.Fat
		s.Fibre += l.Fibre
	}
	return s, nil
}

